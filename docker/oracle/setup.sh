#!/usr/bin/env bash
# One-time setup of InsightAI on a single Ubuntu VM (Oracle Cloud Always Free, Ampere arm64, or any
# Ubuntu 22.04/24.04 server): Docker, firewall, secrets, images, database, storage, daily backup.
# Guide: docs/DEPLOY_ORACLE.md. Run from the repository checkout:
#
#   sudo bash docker/oracle/setup.sh <domain> [alert-webhook-url]
#
# <domain> must already point at this VM (e.g. insightai-demo.duckdns.org); Caddy then obtains the
# HTTPS certificate itself. Re-running is safe: existing secrets are kept, images are rebuilt and
# the stack is updated (migrations are additive).
set -euo pipefail

DOMAIN="${1:?usage: sudo bash docker/oracle/setup.sh <domain> [alert-webhook-url]}"
WEBHOOK="${2:-}"
ETC=/etc/insightai
ENV_FILE="$ETC/production.env"
S3_CONFIG="$ETC/seaweedfs-s3.json"
BACKUP_DIR=/var/backups/insightai
REPO="$(cd "$(dirname "$0")/../.." && pwd)"
PROFILES=(--profile selfhosted-db --profile selfhosted-s3)

[ "$(id -u)" = 0 ] || { echo "run with sudo" >&2; exit 1; }
[ -f "$REPO/docker/compose.prod.yml" ] || { echo "run from the InsightAI repository" >&2; exit 1; }
log() { printf '\n==> %s\n' "$*"; }

log "Docker Engine + Compose (official Docker apt repository)"
if ! command -v docker >/dev/null || ! docker compose version >/dev/null 2>&1; then
  apt-get update -q
  apt-get install -y -q ca-certificates curl gnupg
  install -m 0755 -d /etc/apt/keyrings
  curl -fsSL https://download.docker.com/linux/ubuntu/gpg -o /etc/apt/keyrings/docker.asc
  chmod a+r /etc/apt/keyrings/docker.asc
  . /etc/os-release
  echo "deb [arch=$(dpkg --print-architecture) signed-by=/etc/apt/keyrings/docker.asc] https://download.docker.com/linux/ubuntu ${VERSION_CODENAME} stable" \
    > /etc/apt/sources.list.d/docker.list
  apt-get update -q
  apt-get install -y -q docker-ce docker-ce-cli containerd.io docker-buildx-plugin docker-compose-plugin
fi
systemctl enable --now docker

log "Firewall: allow HTTP/HTTPS (Oracle's Ubuntu images reject them in iptables by default)"
for port in 80 443; do
  iptables -C INPUT -p tcp --dport "$port" -m state --state NEW -j ACCEPT 2>/dev/null \
    || iptables -I INPUT 5 -p tcp --dport "$port" -m state --state NEW -j ACCEPT
done
if command -v netfilter-persistent >/dev/null; then netfilter-persistent save; fi

log "Secrets in $ENV_FILE (kept if it already exists; never printed)"
install -d -m 700 "$ETC"
secret() { openssl rand -base64 48 | tr -d '/+=\n' | cut -c1-"${1:-32}"; }
if [ ! -f "$ENV_FILE" ]; then
  PG=$(secret); OWNER=$(secret); APP=$(secret); PROV=$(secret); ANALYTICS=$(secret)
  INGEST=$(secret); REDIS=$(secret); S3_KEY=$(secret 20); S3_SECRET=$(secret 40)
  umask 077
  cat > "$ENV_FILE" <<EOF
# Generated by docker/oracle/setup.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ). Keep a copy in a password
# manager: the backup passphrase is needed to restore. Variables: docker/production.env.example.
SITE_ADDRESS=$DOMAIN
PORT=3100
LOG_LEVEL=info
JWT_ACCESS_SECRET=$(secret 48)

POSTGRES_SUPERUSER=postgres
POSTGRES_SUPERUSER_PASSWORD=$PG
POSTGRES_DB=insightai
DATABASE_ADMIN_URL=postgresql://postgres:$PG@postgres:5432/insightai
DATABASE_MIGRATE_URL=postgresql://insightai_owner:$OWNER@postgres:5432/insightai?schema=app
DATABASE_URL=postgresql://insightai_app:$APP@postgres:5432/insightai
DATABASE_PROVISIONER_URL=postgresql://insightai_provisioner:$PROV@postgres:5432/insightai
DATABASE_ANALYTICS_URL=postgresql://insightai_analytics:$ANALYTICS@postgres:5432/insightai
DATABASE_INGEST_URL=postgresql://insightai_ingest:$INGEST@postgres:5432/insightai

REDIS_PASSWORD=$REDIS
REDIS_URL=redis://:$REDIS@redis:6379

# SeaweedFS on the internal network (profile selfhosted-s3).
S3_ENDPOINT=http://seaweedfs:8333
S3_REGION=us-east-1
S3_BUCKET=insightai
S3_ACCESS_KEY_ID=$S3_KEY
S3_SECRET_ACCESS_KEY=$S3_SECRET
S3_FORCE_PATH_STYLE=true

AI_DAILY_QUESTION_LIMIT=200
# OPENAI_API_KEY=
# OPENAI_MODEL=
# OPENAI_BASE_URL=

BACKUP_ENCRYPTION_PASSPHRASE=$(secret 40)
# Off-site copy (e.g. Cloudflare R2 / Backblaze B2): BACKUP_S3_BUCKET, BACKUP_S3_ENDPOINT,
# AWS_ACCESS_KEY_ID, AWS_SECRET_ACCESS_KEY.

OPS_STATUS_TOKEN=$(secret 40)
${WEBHOOK:+OPS_ALERT_WEBHOOK_URL=$WEBHOOK}
# OPS_HEARTBEAT_URL=
EOF
  cat > "$S3_CONFIG" <<EOF
{"identities":[{"name":"insightai","credentials":[{"accessKey":"$S3_KEY","secretKey":"$S3_SECRET"}],"actions":["Admin","Read","Write","List","Tagging"]}]}
EOF
  chmod 600 "$ENV_FILE"
  chmod 644 "$S3_CONFIG" # read by the SeaweedFS container; it holds only the storage key
  echo "created $ENV_FILE"
else
  echo "keeping existing $ENV_FILE"
fi

compose() {
  INSIGHTAI_ENV_FILE="$ENV_FILE" SEAWEEDFS_S3_CONFIG="$S3_CONFIG" BACKUP_HOST_DIR="$BACKUP_DIR" \
    docker compose -f "$REPO/docker/compose.prod.yml" --env-file "$ENV_FILE" "${PROFILES[@]}" "$@"
}

log "Build images (native for this machine's architecture: $(uname -m))"
cd "$REPO"
docker build -f apps/api/Dockerfile -t insightai-api:latest .
docker build -f apps/api/Dockerfile --target migrate -t insightai-migrate:latest .
docker build -f apps/web/Dockerfile -t insightai-web:latest .
docker build docker/backup -t insightai-backup:latest

log "Database, cache, storage; bucket"
compose up -d postgres redis seaweedfs
compose run --rm --no-deps migrate node scripts/ensure-bucket.mjs

log "Start InsightAI (migrations run first)"
compose up -d
for i in $(seq 1 60); do
  if compose exec -T api node -e "fetch('http://127.0.0.1:3100/health/ready').then(r=>process.exit(r.ok?0:1)).catch(()=>process.exit(1))" 2>/dev/null; then
    echo "API ready"; break
  fi
  [ "$i" = 60 ] && { echo "API not ready after 5 minutes: docker compose logs api" >&2; exit 1; }
  sleep 5
done

log "Daily encrypted backup at 02:00 (kept 7 days in $BACKUP_DIR)"
install -d -m 700 "$BACKUP_DIR"
chown 70:70 "$BACKUP_DIR" # uid of the postgres user in the backup image
cat > /etc/cron.d/insightai-backup <<EOF
0 2 * * * root bash $REPO/docker/oracle/ops.sh --profile backup run --rm backup >> /var/log/insightai-backup.log 2>&1
EOF

log "Done"
cat <<EOF
InsightAI: https://$DOMAIN  (the certificate can take a minute on first start)
Next (docs/DEPLOY_ORACLE.md §5):
  sudo docker run --rm -v $REPO/docker:/s:ro node:24.18.0-bookworm-slim node /s/smoke.mjs https://$DOMAIN
  sudo bash docker/oracle/ops.sh run --rm worker node dist/ops-alert-test.js
Secrets: $ENV_FILE (root only). Back it up somewhere safe.
EOF
