# Runs the production stack on this Windows machine (Docker Desktop) and publishes it through a
# Cloudflare Tunnel: no open ports, HTTPS at Cloudflare, data stays on this machine (D-61).
# Guide: docs/DEPLOY_LOCAL_TUNNEL.md. From the repository root:
#
#   powershell -ExecutionPolicy Bypass -File docker\local\setup.ps1                 # quick tunnel (demo)
#   powershell -ExecutionPolicy Bypass -File docker\local\setup.ps1 -ScheduleBackup # + daily 02:00 backup
#
# Named tunnel (stable hostname, needed for AI answers over SSE): put CLOUDFLARE_TUNNEL_TOKEN in the env
# file (see the guide) and run again. Re-running is safe: secrets are kept, images rebuilt, stack updated.
param(
  [string]$Dir = (Join-Path $env:USERPROFILE 'InsightAI-prod'),
  [switch]$ScheduleBackup,
  # Only this machine/LAN (http://localhost:8088), no public tunnel.
  [switch]$NoTunnel
)
$ErrorActionPreference = 'Stop'
$Repo = (Resolve-Path (Join-Path $PSScriptRoot '..\..')).Path
$EnvFile = Join-Path $Dir 'production.env'
$S3Config = Join-Path $Dir 'seaweedfs-s3.json'
function Log($text) { Write-Host "`n==> $text" -ForegroundColor Cyan }
function Write-NoBom($path, $text) {
  [IO.File]::WriteAllText($path, $text, (New-Object Text.UTF8Encoding $false))
}
function New-Secret([int]$length = 32) {
  $chars = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789'.ToCharArray()
  $bytes = New-Object byte[] $length
  [Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($bytes)
  -join ($bytes | ForEach-Object { $chars[$_ % $chars.Length] })
}

docker info --format '{{.ServerVersion}}' *> $null
if ($LASTEXITCODE -ne 0) { throw 'Docker Desktop is not running: start it first.' }

Log "Secrets in $EnvFile (kept if it already exists; never printed)"
New-Item -ItemType Directory -Force -Path $Dir, (Join-Path $Dir 'backups') | Out-Null
if (-not (Test-Path $EnvFile)) {
  $pg = New-Secret; $owner = New-Secret; $app = New-Secret; $prov = New-Secret
  $analytics = New-Secret; $ingest = New-Secret; $redis = New-Secret
  $s3Key = New-Secret 20; $s3Secret = New-Secret 40
  $stamp = (Get-Date).ToUniversalTime().ToString('yyyy-MM-ddTHH:mm:ssZ')
  $text = @"
# Generated by docker/local/setup.ps1 on $stamp. Keep a copy in a password manager: the backup
# passphrase is needed to restore. Variables: docker/production.env.example.
SITE_ADDRESS=:80
HTTP_PORT=8088
HTTPS_PORT=8448
# Behind Cloudflare Tunnel: Cloudflare -> cloudflared -> Caddy -> API.
CADDY_TRUSTED_PROXIES=private_ranges
TRUST_PROXY_HOPS=2
# Named tunnel token (Cloudflare Zero Trust -> Networks -> Tunnels); empty = quick tunnel.
CLOUDFLARE_TUNNEL_TOKEN=
PORT=3100
LOG_LEVEL=info
JWT_ACCESS_SECRET=$(New-Secret 48)

POSTGRES_SUPERUSER=postgres
POSTGRES_SUPERUSER_PASSWORD=$pg
POSTGRES_DB=insightai
DATABASE_ADMIN_URL=postgresql://postgres:$pg@postgres:5432/insightai
DATABASE_MIGRATE_URL=postgresql://insightai_owner:$owner@postgres:5432/insightai?schema=app
DATABASE_URL=postgresql://insightai_app:$app@postgres:5432/insightai
DATABASE_PROVISIONER_URL=postgresql://insightai_provisioner:$prov@postgres:5432/insightai
DATABASE_ANALYTICS_URL=postgresql://insightai_analytics:$analytics@postgres:5432/insightai
DATABASE_INGEST_URL=postgresql://insightai_ingest:$ingest@postgres:5432/insightai

REDIS_PASSWORD=$redis
REDIS_URL=redis://:$redis@redis:6379

S3_ENDPOINT=http://seaweedfs:8333
S3_REGION=us-east-1
S3_BUCKET=insightai
S3_ACCESS_KEY_ID=$s3Key
S3_SECRET_ACCESS_KEY=$s3Secret
S3_FORCE_PATH_STYLE=true

AI_DAILY_QUESTION_LIMIT=200
# OPENAI_API_KEY=
# OPENAI_MODEL=
# OPENAI_BASE_URL=

BACKUP_ENCRYPTION_PASSPHRASE=$(New-Secret 40)
OPS_STATUS_TOKEN=$(New-Secret 40)
# OPS_ALERT_WEBHOOK_URL=
# OPS_HEARTBEAT_URL=
"@
  Write-NoBom $EnvFile ($text -replace "`r`n", "`n")
  Write-NoBom $S3Config "{`"identities`":[{`"name`":`"insightai`",`"credentials`":[{`"accessKey`":`"$s3Key`",`"secretKey`":`"$s3Secret`"}],`"actions`":[`"Admin`",`"Read`",`"Write`",`"List`",`"Tagging`"]}]}"
  # Only the current user may read the secrets.
  icacls $Dir /inheritance:r /grant:r "${env:USERNAME}:(OI)(CI)F" | Out-Null
  Write-Host "created $EnvFile"
} else {
  Write-Host "keeping existing $EnvFile"
}

$ops = Join-Path $PSScriptRoot 'ops.ps1'
$env:INSIGHTAI_PROD_DIR = $Dir
$env:INSIGHTAI_NO_TUNNEL = if ($NoTunnel) { '1' } else { '' }
function Compose { & $ops @args; if ($LASTEXITCODE -ne 0) { throw "docker compose $args failed" } }

Log 'Build images'
Push-Location $Repo
try {
  docker build -f apps/api/Dockerfile -t insightai-api:latest .
  if ($LASTEXITCODE -ne 0) { throw 'api image build failed' }
  docker build -f apps/api/Dockerfile --target migrate -t insightai-migrate:latest .
  if ($LASTEXITCODE -ne 0) { throw 'migrate image build failed' }
  docker build -f apps/web/Dockerfile -t insightai-web:latest .
  if ($LASTEXITCODE -ne 0) { throw 'web image build failed' }
  docker build docker/backup -t insightai-backup:latest
  if ($LASTEXITCODE -ne 0) { throw 'backup image build failed' }
} finally { Pop-Location }

Log 'Database, cache, storage; bucket'
Compose up -d postgres redis seaweedfs
Compose run --rm --no-deps migrate node scripts/ensure-bucket.mjs

Log 'Start InsightAI and the tunnel (migrations run first)'
Compose up -d
$ready = $false
for ($i = 0; $i -lt 60 -and -not $ready; $i++) {
  try { $ready = (Invoke-WebRequest -UseBasicParsing -TimeoutSec 3 'http://localhost:8088/health/ready').StatusCode -eq 200 } catch { Start-Sleep 5 }
}
if (-not $ready) { throw 'API not ready after 5 minutes: docker\local\ops.ps1 logs api' }
Write-Host 'API ready (local check: http://localhost:8088)'

$named = @(Get-Content $EnvFile | Where-Object { $_ -match '^CLOUDFLARE_TUNNEL_TOKEN=.+' }).Count -gt 0
if ($NoTunnel) {
  Log 'No tunnel: http://localhost:8088 on this machine only'
} elseif ($named) {
  Log 'Named tunnel started: open the hostname you set in the Cloudflare dashboard'
} else {
  Log 'Quick tunnel URL (changes on every restart; AI streaming answers need a named tunnel)'
  $url = $null
  for ($i = 0; $i -lt 30 -and -not $url; $i++) {
    $logs = (& $ops logs cloudflared-quick 2>&1) -join "`n"
    if ($logs -match 'https://[a-z0-9-]+\.trycloudflare\.com') { $url = $Matches[0] } else { Start-Sleep 2 }
  }
  if ($url) { Write-Host $url -ForegroundColor Green } else { Write-Host 'URL not found yet: docker\local\ops.ps1 logs cloudflared-quick' }
}

if ($ScheduleBackup) {
  Log 'Daily encrypted backup at 02:00 (Task Scheduler, runs when you are logged on)'
  $action = New-ScheduledTaskAction -Execute 'powershell.exe' -Argument "-NoProfile -ExecutionPolicy Bypass -Command `"`$env:INSIGHTAI_PROD_DIR='$Dir'; & '$ops' --profile backup run --rm backup`""
  $trigger = New-ScheduledTaskTrigger -Daily -At 2am
  $settings = New-ScheduledTaskSettingsSet -StartWhenAvailable -WakeToRun
  Register-ScheduledTask -TaskName 'InsightAI backup' -Action $action -Trigger $trigger -Settings $settings -Force | Out-Null
  Write-Host "scheduled; backups in $(Join-Path $Dir 'backups')"
}

Log 'Done'
Write-Host "Secrets: $EnvFile (only your Windows user can read it). Copy it to a password manager."
